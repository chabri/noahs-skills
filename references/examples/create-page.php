<?php

/**
 * @file
 * Example: create (or update) a landing page built with Noahs widgets. Idempotent: run it as often as you like.
 *
 * Usage (from the project root, kit copied to noahs-build/kit):
 *   noahs-build/kit/noahs.sh run noahs-build/examples/create-page.php /example-landing [path/to/hero.jpg]
 *   noahs-build/kit/noahs.sh css node <nid printed above>
 *
 * Free widgets only; when Noahs Pro is enabled it also adds entrance / cascade animations (Pro "Extras").
 */

require_once __DIR__ . '/../kit/php/lib.php';
require_once __DIR__ . '/hero-section.php';

$alias = $extra[0] ?? '/example-landing';
$image = $extra[1] ?? '';
$pro = noahs_is_pro();
$seed = 'example-landing';

$node = noahs_ensure_node($alias, 'Example landing', 'page');

// 1. Hero ------------------------------------------------------------------------------------------------------------
$media = NULL;
if ($image !== '') {
  // Relative paths are resolved from the project root (drush runs inside the Drupal docroot).
  $path = str_starts_with($image, '/') ? $image : dirname(DRUPAL_ROOT) . '/' . $image;
  $media = noahs_media_from_file($path, 'Example landing hero', 'Team working together in a bright studio');
}
$sections[] = example_hero("$seed-hero", [
  'eyebrow' => 'Built with Noah\'s Page Builder',
  'title' => 'Launch beautiful Drupal pages in minutes',
  'intro' => 'Sections, columns and widgets you can keep editing visually after they are generated by code.',
  'primary_label' => 'Get started',
  'primary_url' => '/contact',
  'secondary_label' => 'See features',
  // Anchor to a section: every widget renders with id="widget-id-<wid>".
  'secondary_url' => '#widget-id-' . noahs_wid("$seed-features"),
], $media, $pro);

// 2. Features: three columns with icon + heading + text ---------------------------------------------------------------
$features = [
  ['fa-solid fa-layer-group', 'Visual sections', 'Rows, columns and nested sections with responsive widths and spacing.'],
  ['fa-solid fa-palette', 'Global styles', 'Fonts, colors and buttons defined once in Settings and Global styles.'],
  ['fa-solid fa-bolt', 'Fast to build', 'Reusable blocks, views and templates for every part of the site.'],
];
$cols = [];
foreach ($features as $i => [$icon, $title, $text]) {
  $cols[] = noahs_column("$seed-feat-c$i", [
    noahs_widget('noahs_icon', "$seed-feat-icon$i", [
      'icon' => ['class' => $icon, 'fid' => '', 'url' => ''],
      'css.desktop.default.horizontal_align' => 'flex-start',
      'css.desktop.default.color' => '#2563EB',
    ]),
    noahs_widget('noahs_heading', "$seed-feat-h$i", [
      'heading_text.text' => $title,
      'heading_type' => 'h3',
    ] + noahs_font('font', ['font_size' => '22px', 'margin_top' => '16px', 'margin_bottom' => '8px'])),
    noahs_widget('noahs_text', "$seed-feat-t$i", [
      // Always replace the default text of a widget: defaults contain placeholder copy.
      'text' => "<p>$text</p>",
    ] + noahs_font('font', ['font_size' => '16px', 'line_height' => '1.6', 'color' => '#4B5563'])),
  ], ['calc(33.333% - 20px)', 'calc(50% - 15px)', '100%'], [
    'css.desktop.default.bg_color' => '#FFFFFF',
    'css.desktop.default.padding' => noahs_box('padding', '32px', '28px', '32px', '28px'),
    'css.desktop.default.widget_border_radius' => noahs_radius('16px'),
    'css.desktop.default.border' => noahs_border('#E5E7EB'),
  ] + ($pro ? noahs_hover_transform(['translate_y' => '-4px']) : []));
}
$sections[] = noahs_section("$seed-features", $cols, [
  'css.desktop.default.bg_color' => '#F9FAFB',
  'css.desktop.default.section_columns_gap.text' => '30px',
  'css.desktop.default.columns_position' => 'stretch',
] + noahs_resp('padding', [
  noahs_box('padding', '90px', '15px', '90px', '15px'),
  noahs_box('padding', '70px', '15px', '70px', '15px'),
  noahs_box('padding', '50px', '15px', '50px', '15px'),
]) + ($pro ? noahs_motion_cascade('fade-up', 120) : []));

// 3. Call to action ---------------------------------------------------------------------------------------------------
$sections[] = noahs_section("$seed-cta", [
  noahs_column("$seed-cta-c", [
    noahs_widget('noahs_heading', "$seed-cta-h", [
      'heading_text.text' => 'Ready to build your next site?',
      'heading_type' => 'h2',
      'css.desktop.default.text_align' => 'center',
    ] + noahs_font('font', ['color' => '#FFFFFF'])),
    noahs_widget('noahs_button', "$seed-cta-btn", [
      'button_title.text' => 'Contact us',
      'button_url' => noahs_url_value('/contact'),
      'css.desktop.default.button_horizontal_align' => 'center',
    ]),
  ], ['100%'], ['css.desktop.default.elements_gap.text' => '24px']),
], [
  'css.desktop.default.bg_color' => '#2563EB',
] + noahs_resp('padding', [
  noahs_box('padding', '80px', '15px', '80px', '15px'),
  NULL,
  noahs_box('padding', '56px', '15px', '56px', '15px'),
]));

noahs_save_page('node', $node->id(), $sections, $node->language()->getId());
echo "Saved Noahs design for node " . $node->id() . " ($alias), " . count($sections) . " sections" . ($pro ? ' (Pro animations on)' : '') . "." . PHP_EOL;
echo "Next: noahs.sh css node " . $node->id() . PHP_EOL;
